export const getPlantById = (id) =>
  plantDatabase.find((p) => p.id === id) || null;

export const getCompanionDetails = (plant) => {
  const good = plant.companions
    .map((id) => getPlantById(id))
    .filter(Boolean);
  const avoid = plant.avoids
    .map((id) => getPlantById(id))
    .filter(Boolean);
  return { good, avoid };
};
